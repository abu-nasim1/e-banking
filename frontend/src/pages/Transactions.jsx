import { useEffect, useState } from 'react';
import { FileDown } from 'lucide-react';
import api from '../api/axios';

const today = new Date().toISOString().slice(0, 10);
const initialFrom = new Date(Date.now() - 30 * 24 * 60 * 60 * 1000).toISOString().slice(0, 10);
const currency = (value) => `BDT ${Number(value || 0).toLocaleString('en-BD', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

export default function Transactions() {
  const [accounts, setAccounts] = useState([]);
  const [transactions, setTransactions] = useState([]);
  const [accountId, setAccountId] = useState('');
  const [from, setFrom] = useState(initialFrom);
  const [to, setTo] = useState(today);
  const [loading, setLoading] = useState(true);
  const [downloading, setDownloading] = useState(false);
  const [error, setError] = useState('');

  useEffect(() => {
    Promise.all([api.get('/accounts/my'), api.get('/transactions')])
      .then(([accountResponse, transactionResponse]) => {
        const accountList = Array.isArray(accountResponse.data) ? accountResponse.data : [];
        setAccounts(accountList);
        setAccountId(accountList[0]?.id || '');
        setTransactions(Array.isArray(transactionResponse.data) ? transactionResponse.data : []);
      })
      .catch(() => setError('Could not load transaction data. Please check the backend connection.'))
      .finally(() => setLoading(false));
  }, []);

  const downloadStatement = async (event) => {
    event.preventDefault();
    setError('');
    if (!accountId || !from || !to || from > to) {
      setError('Choose an account and a valid date range.');
      return;
    }

    setDownloading(true);
    try {
      const [{ jsPDF }, { default: autoTable }] = await Promise.all([
        import('jspdf'),
        import('jspdf-autotable'),
      ]);
      const { data } = await api.get('/transactions/statement', { params: { accountId, from, to } });
      const document = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
      const account = data.account;
      const credits = data.transactions
        .filter((transaction) => ['DEPOSIT', 'TRANSFER_IN'].includes(transaction.type))
        .reduce((total, transaction) => total + Number(transaction.amount), 0);
      const debits = data.transactions
        .filter((transaction) => ['WITHDRAW', 'TRANSFER_OUT'].includes(transaction.type))
        .reduce((total, transaction) => total + Number(transaction.amount), 0);

      document.setFont('helvetica', 'bold');
      document.setFontSize(18);
      document.text('E-Bank Account Statement', 15, 18);
      document.setFont('helvetica', 'normal');
      document.setFontSize(10);
      document.text(`Account holder: ${account.user.name}`, 15, 27);
      document.text(`Email: ${account.user.email}`, 15, 33);
      document.text(`Account: ${account.accountNumber} (${account.type})`, 15, 39);
      document.text(`Statement period: ${from} to ${to}`, 15, 45);
      document.text(`Opening balance: ${currency(data.openingBalance)}`, 15, 53);
      document.text(`Total credits: ${currency(credits)}`, 145, 53);
      document.text(`Closing balance: ${currency(data.closingBalance)}`, 15, 59);
      document.setFont('helvetica', 'normal');
      document.text(`Total debits: ${currency(debits)}`, 145, 59);

      autoTable(document, {
        startY: 64,
        head: [['Date / time', 'Type', 'Description', 'Credit', 'Debit', 'Balance after']],
        body: data.transactions.map((transaction) => {
          const isCredit = ['DEPOSIT', 'TRANSFER_IN'].includes(transaction.type);
          return [
            new Date(transaction.createdAt).toLocaleString('en-GB'),
            transaction.type.replaceAll('_', ' '),
            transaction.description || '-',
            isCredit ? currency(transaction.amount) : '-',
            isCredit ? '-' : currency(transaction.amount),
            currency(transaction.balanceAfter),
          ];
        }),
        styles: { font: 'helvetica', fontSize: 8, cellPadding: 2.5, overflow: 'linebreak' },
        headStyles: { fillColor: [23, 87, 67], textColor: [255, 255, 255] },
        alternateRowStyles: { fillColor: [242, 247, 244] },
        columnStyles: { 0: { cellWidth: 34 }, 1: { cellWidth: 27 }, 2: { cellWidth: 'auto' }, 3: { cellWidth: 32 }, 4: { cellWidth: 32 }, 5: { cellWidth: 36 } },
        didDrawPage: () => {
          document.setFontSize(8);
          document.setFont('helvetica', 'normal');
          document.text('Generated by E-Bank', 15, 202);
          document.text(`Page ${document.internal.getNumberOfPages()}`, 282, 202);
        },
      });

      document.save(`statement-${account.accountNumber}-${from}-to-${to}.pdf`);
    } catch (requestError) {
      setError(requestError.response?.data?.message || 'Could not download the statement. Please try again.');
    } finally {
      setDownloading(false);
    }
  };

  return (
    <div className="transactions-page">
      <div className="transactions-heading">
        <div>
          <span className="eyebrow">YOUR ACTIVITY</span>
          <h1>Transactions</h1>
          <p>Review your recent activity or download an account statement.</p>
        </div>
      </div>

      {error && <div className="box transaction-error" role="alert">{error}</div>}

      <form className="box statement-download" onSubmit={downloadStatement}>
        <div className="statement-download-heading">
          <div><h2>Download statement</h2><p>Choose an account and statement period.</p></div>
          <FileDown size={20} aria-hidden="true" />
        </div>
        <div className="statement-filters">
          <label>Account<select value={accountId} onChange={(event) => setAccountId(event.target.value)} required disabled={!accounts.length}><option value="">Select account</option>{accounts.map((account) => <option key={account.id} value={account.id}>{account.type} · {account.accountNumber}</option>)}</select></label>
          <label>From<input type="date" value={from} max={to} onChange={(event) => setFrom(event.target.value)} required /></label>
          <label>To<input type="date" value={to} min={from} max={today} onChange={(event) => setTo(event.target.value)} required /></label>
          <button type="submit" disabled={loading || downloading || !accounts.length}><FileDown size={16} />{downloading ? 'Preparing PDF…' : 'Download PDF'}</button>
        </div>
      </form>

      <section className="box transaction-history">
        <div className="transaction-history-heading"><div><h2>Recent transaction history</h2><p>Latest 100 entries across your accounts.</p></div></div>
        {loading ? <p>Loading transactions…</p> : transactions.length ? transactions.map((transaction) => (
          <div key={transaction.id} className="row">
            <span>{new Date(transaction.createdAt).toLocaleString()} · {transaction.type.replaceAll('_', ' ')} · {transaction.account?.accountNumber}</span>
            <b>{currency(transaction.amount)}</b>
          </div>
        )) : <p>No transaction yet.</p>}
      </section>
    </div>
  );
}